  await js("document.querySelector('[aria-controls=deliverables-panel]').click()")
  await wait("!document.querySelector('.deliverables-panel')")
  await js("document.querySelector('[aria-controls=deliverables-panel]').click()")
  await wait("document.querySelectorAll('.artifact-card').length===1")
  await wait("document.querySelectorAll('.agent-message[open]').length===1&&[...document.querySelectorAll('.agent-message')].at(-1).open")
  await new Promise(r=>setTimeout(r,350))
  await js("[...document.querySelectorAll('.agent-message[open] .markdown a')].find(a=>a.textContent==='下载PPT').click()")
  await wait("!document.querySelector('.toast')")
  if(!fs.existsSync(path.join(directory,'opened-artifact.json')))throw new Error('Markdown file link did not reach the validated artifact opener')
  const opened=JSON.parse(fs.readFileSync(path.join(directory,'opened-artifact.json'),'utf8'))
  const registered=await js('window.qwork.get().then(s=>s.artifacts[0].id)')
  if(opened.id!==registered)throw new Error('Markdown opened the wrong artifact')
  await js("[...document.querySelectorAll('.agent-message[open] .markdown a')].find(a=>a.textContent==='无效文件').click()")
  await wait("document.querySelector('.toast')?.textContent.includes('未找到对应的交付文件')")
  await js("document.querySelector('.toast button').click()")
  await capture('02-delivery.png')
  await js("document.querySelector('.live-preview').open=true")
  await wait("document.querySelectorAll('.live-agent-tabs button').length===3")
  if(!await js("document.querySelector('.live-agent-tabs button').getAttribute('aria-selected')==='true'"))throw new Error('First round response tab must be selected')
  if(await js("!!document.querySelector('.live-agent-tabs .response-running')"))throw new Error('Completed replies still show a responding animation')
  await js("document.querySelector('.live-preview').open=false")

  await js("document.querySelector('.diagram-agent').click()")
  await wait("!!document.querySelector('.trace-drawer[open]')&&document.querySelectorAll('.attempt-card').length>0")
  await capture('07-agent-trace.png')
  await js("document.querySelector('.trace-drawer .dialog-header button').click()")
